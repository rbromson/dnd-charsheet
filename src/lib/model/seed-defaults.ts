/**
 * Персонажи по умолчанию — Фрідо Брецель по листам игрока:
 *  • «Простолюдин 1 (Трактирник)» — основной лист;
 *  • «Вампір 5 (Тіньова рука)» — лист от майстра «на випадок звернення».
 * В листе вампира цифры не заполнены: характеристики взяты с листа 1 уровня
 * (повышение на 4 уровне оставлено игроку), ОЗ — среднее по 5к10, КО — 10 + Спр + Стат.
 */

export interface SeedCharacter {
  character: Character;
  codex: Omit<CodexEntry, 'id' | 'characterId' | 'createdAt' | 'updatedAt'>[];
  /** путь к портрету относительно BASE_URL */
  portrait: string;
  /** дополнительные картинки в галерею */
  gallery: string[];
}

const atk = (a: Partial<Attack> & Pick<Attack, 'name' | 'ability' | 'damage' | 'damageType'>): Attack => ({
  id: uid(),
  prof: true,
  bonus: 0,
  override: null,
  note: '',
  itemId: null,
  save: null,
  saveDc: null,
  ...a,
});
const item = (name: string, qty = 1, text = '', magic = false): Item => newItem({ name, qty, text, magic });
const spell = (level: number, name: string, text: string, prepared = true): Spell => ({ id: uid(), level, name, text, prepared });
const feat = (name: string, text: string) => ({ id: uid(), name, text });

